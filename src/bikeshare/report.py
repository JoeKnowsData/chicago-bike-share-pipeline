"""Run the analysis queries in analysis/ and write their results to a Markdown file,
so the findings in the README can be regenerated from the data at any time."""

from __future__ import annotations

import logging
from datetime import datetime
from pathlib import Path

import duckdb

from bikeshare.config import REPO_ROOT

log = logging.getLogger(__name__)

ANALYSIS_DIR = REPO_ROOT / "analysis"


def _title(sql: str, fallback: str) -> str:
    for line in sql.splitlines():
        if line.startswith("-- Q:"):
            return line.removeprefix("-- Q:").strip()
    return fallback


def _markdown_table(columns: list[str], rows: list[tuple]) -> str:
    def fmt(value: object) -> str:
        if value is None:
            return ""
        if isinstance(value, float):
            return f"{value:,.2f}"
        if isinstance(value, int) and not isinstance(value, bool):
            return f"{value:,}"
        return str(value).replace("|", "\\|")

    header = "| " + " | ".join(columns) + " |"
    divider = "| " + " | ".join("---" for _ in columns) + " |"
    body = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join([header, divider, *body])


def write_report(con: duckdb.DuckDBPyConnection, dest: Path, analysis_dir: Path = ANALYSIS_DIR):
    sections = [
        "# Analysis results",
        "",
        f"Generated by `bikeshare report` on {datetime.now():%Y-%m-%d}. "
        "Each section is one query in [`analysis/`](../analysis).",
    ]
    for sql_file in sorted(analysis_dir.glob("*.sql")):
        sql = sql_file.read_text(encoding="utf-8")
        result = con.execute(sql)
        columns = [c[0] for c in result.description]
        rows = result.fetchall()
        sections += [
            "",
            f"## {_title(sql, sql_file.stem)}",
            "",
            f"Query: [`analysis/{sql_file.name}`](../analysis/{sql_file.name})",
            "",
            _markdown_table(columns, rows),
        ]
        log.info("ran analysis %s (%s rows)", sql_file.name, len(rows))
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(sections) + "\n", encoding="utf-8")
    return dest
